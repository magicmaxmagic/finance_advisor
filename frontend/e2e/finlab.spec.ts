for (const width of [1280,768,390]) {
  test(`company and comparison are usable at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width,height: 900 })
    await page.goto(`/${historical}#company-research/AAPL`)
    await expect(page.locator('.hero-score')).toContainText('70.6')
    await capture(page,`company-${width}`)
    await page.getByRole('button',{name:'Add to comparison',exact:true}).click()
    if (width <= 850) await page.getByRole('button',{name:'Toggle navigation'}).click()
    await page.getByRole('button',{name:'Compare',exact:true}).click()
    await page.getByLabel('Add comparison company').selectOption('MSFT')
    await expect(page.getByRole('columnheader',{name:/MSFT/i})).toBeVisible()
    if (width === 390) {
      const right = await page.getByRole('columnheader',{name:/MSFT/i}).boundingBox()
      expect(right && right.x + right.width <= width).toBe(true)
    }
    await capture(page,`compare-${width}`)
  })
}
