import { expect, test, type Page } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'

const screenshots = resolve(process.cwd(), '../data/reports/ui-v4/final')
const historical = '?as_of=2020-12-31'

async function capture(page: Page, name: string) {
  await mkdir(screenshots, { recursive: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: resolve(screenshots, `${name}.png`) })
}

test.beforeEach(async ({ context, baseURL }) => {
  const origin = new URL(baseURL!).origin
  await context.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort())
})

test('Overview → company → evidence → compare → discovery preset', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => {
    if (message.type() === 'error' && message.text().includes('same key')) errors.push(message.text())
  })
  await page.goto('/#overview')
  await expect(page.getByRole('heading', { name: 'Top research opportunities' })).toBeVisible()
  await capture(page, 'overview-1440')
  await page.getByRole('searchbox', { name: 'Search companies' }).fill('AAPL')
  await page.getByRole('button', { name: /AAPL.*Apple/i }).click()
  await expect(page.getByRole('heading', { name: /Apple Inc/i })).toBeVisible()
  await page.getByLabel('Research cutoff date').fill('2020-12-31')
  await expect(page.locator('.hero-score')).toContainText('70.6')
  await capture(page, 'company-1440')
  await page.getByRole('button', { name: 'Explain Fiscal-year P/E', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Fiscal-year P/E' })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Quant', exact: true }).click()
  await expect(dialog.getByRole('heading', { name: 'Formula and provenance' })).toBeVisible()
  await expect(dialog).toContainText('Filed')
  await expect(dialog.getByText('Observed range', { exact: true })).toBeVisible()
  await expect(dialog.getByText(/archived study includes outcomes after this cutoff/)).toBeVisible()
  await capture(page, 'valuation-drawer-1440')
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Explain Fiscal-year P/E', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Market & events', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Recorded company events' })).toBeVisible()
  await expect(page.getByText('SEC 10-K', { exact: true }).first()).toBeVisible()
  await capture(page, 'market-events-1440')
  const events = page.getByRole('button', { name: /Show all \d+ events/ })
  await events.click()
  await expect(page.getByRole('button', { name: 'Show latest five events' })).toHaveAttribute('aria-expanded', 'true')
  await page.getByRole('button', { name: 'Show latest five events' }).click()
  await expect(events).toHaveAttribute('aria-expanded', 'false')
  const price = page.locator('.price-chart').filter({ has: page.getByRole('heading', { name: 'Price history', exact: true }) })
  await price.getByRole('button', { name: '3M', exact: true }).click()
  await price.getByRole('button', { name: 'SMA50', exact: true }).click()
  await price.getByRole('button', { name: 'SPY', exact: true }).click()
  await expect(price.getByText('Price return excludes reinvested dividends.', { exact: false })).toBeVisible()
  await capture(page, 'chart-1440')
  await page.getByRole('button', { name: 'Add to comparison', exact: true }).click()
  await page.getByRole('button', { name: 'Compare', exact: true }).click()
  await page.getByLabel('Add comparison company').selectOption('MSFT')
  await expect(page.getByRole('table', { name: '', exact: true })).toContainText('MSFT')
  await expect(page.getByRole('columnheader', { name: /AAPL/i })).toBeVisible()
  await capture(page, 'compare-1440')
  await page.getByRole('button', { name: 'Open Discover' }).click()
  await page.getByRole('button', { name: 'Strong fundamentals', exact: true }).click()
  await expect(page.getByText('Fundamental score of at least 65.')).toBeVisible()
  await expect(page.getByRole('button', { name: /Compare selected · 2/ })).toBeVisible()
  await capture(page, 'discover-1440')
  expect(errors).toEqual([])
})

test('portfolio records, values, edits and removes a holding without CSV', async ({ page }) => {
  await page.goto(`/${historical}#portfolio/AAPL`)
  await page.getByLabel('Company name or ticker').fill('AAPL')
  await page.getByLabel('Transaction date').fill('2020-01-02')
  await page.getByLabel('Quantity', { exact: true }).fill('10')
  await page.getByLabel('Price per share').fill('100')
  await page.getByRole('button', { name: 'Save transaction' }).click()
  await expect(page.getByText('Transaction saved.')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Positions and risk' })).toBeVisible()
  await expect(page.getByText('$1,000.00', { exact: true })).toBeVisible()
  await capture(page, 'portfolio-1440')
  await page.reload()
  await page.getByRole('button', { name: 'Edit AAPL transaction' }).click()
  await page.getByLabel('Quantity', { exact: true }).fill('20')
  await page.getByRole('button', { name: 'Save transaction' }).click()
  await expect(page.getByText('Transaction updated.')).toBeVisible()
  await expect(page.getByText('$2,000.00', { exact: true })).toBeVisible()
  await page.getByLabel('Transaction type').selectOption('sell')
  await page.getByLabel('Transaction date').fill('2020-12-30')
  await page.getByLabel('Quantity', { exact: true }).fill('9999')
  await page.getByLabel('Price per share').fill('125')
  await page.getByRole('button', { name: 'Save transaction' }).click()
  await expect(page.getByRole('alert').filter({ hasText: /sale|sell|holding|quantity/i })).toBeVisible()
  await page.getByLabel('Quantity', { exact: true }).fill('1')
  await page.getByRole('button', { name: 'Save transaction' }).click()
  await expect(page.getByText('Transaction saved.')).toBeVisible()
  const sale = page.getByRole('row').filter({hasText:'2020-12-30'})
  await sale.getByRole('button', { name: 'Remove AAPL transaction' }).click()
  await page.getByRole('button', { name: 'Confirm removal' }).click()
  await expect(sale).toHaveCount(0)
  await page.getByRole('button', { name: 'Remove AAPL transaction' }).click()
  await page.getByRole('button', { name: 'Confirm removal' }).click()
  await expect(page.getByText('Transaction removed.')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Transaction history' })).toHaveCount(0)
})

